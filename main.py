import os
from openai import OpenAI

# الكود يسحب المفتاح تلقائياً من سيرفر Railway بأمان
API_KEY = os.environ.get("OPENAI_API_KEY")

if not API_KEY:
    raise ValueError("⚠️ خطأ: لم يتم العثور على مفتاح OPENAI_API_KEY في متغيرات السيرفر!")

client = OpenAI(api_key=API_KEY)

def analyze_market_data(raw_data):
    system_instruction = (
        "أنت خبير محترف ومحلل بيانات متقدم في أبحاث السوق والمشاريع الناشئة (SaaS). "
        "مهمتك هي تحليل البيانات الخام القادمة من منصات التواصل ومواقع العمل الحر بدقة، "
        "واستخراج أفضل 10 خدمات رقمية عليها أعلى نسبة طلب وفرص نمو من قبل الأفراد والمؤسسات الصغيرة. "
        "يجب أن تركز بشكل أساسي على الخدمات التي يمكن أتمتتها بالكامل عبر بوت ذكاء اصطناعي (AI Agent) دون تدخل بشري. "
        "قم بتنظيم التقرير النهائي في نقاط تفصيلية واضحة تشمل: اسم الخدمة، نسبة الطلب والاهتمام بناءً على البيانات، "
        "تقييم سهولة الأتمتة البرمجية من 10 مع شرح السبب، والتوصية الاستراتيجية لكيفية تنفيذها كمنتج رقمي."
    )
    try:
        response = client.chat.completions.create(
            model="gpt-4o-mini",
            messages=[
                {"role": "system", "content": system_instruction},
                {"role": "user", "content": f"إليك البيانات الخام المجمعة من السوق للتحليل والفرز الشامل:\n\n{raw_data}"}
            ],
            temperature=0.4
        )
        return response.choices[0].message.content
    except Exception as e:
        return f"حدث خطأ أثناء الاتصال بالـ API: {str(e)}"

sample_scraped_data = """
- تغريدة 1: يا جماعة أبي أحد يترجم لي هذا الملف الإنجليزي لغة عربية احترافية بدون ترجمة جوجل ركيكة، ضروري اليوم.
- مستخدم في مستقل: مطلوب كاتب محتوى يجهز لي خطة تسويقية وتغريدات وسكريبتات تيك توك لمتجر عطور بشكل أسبوعي.
- تغريدة 2: كيف أقدر أعبي نموذج الجوازات الجديد حق التابعين؟ كل شوية يطلع لي خطأ وأنا أعبي البيانات يدوياً.
- تعليق تيك توك: أنا عندي اجتماع زوم ساعتين وأبي أحد يفرغه لي ويفرز لي النقاط المهمة لأن ما عندي وقت أسمعه كله.
- تغريدة 3: مطلوب مصمم لوقو (شعار) سريع وبسيط لمقهى جديد، الميزانية محدودة والتسليم فوري.
- مستخدم في خمسات: أبحث عن شخص يعدل لي السيرة الذاتية حقتي لتتوافق مع نظام الـ ATS للشركات الكبيرة.
- تغريدة 4: كيف أصيغ عقد اتفاقية عدم إفصاح (NDA) بيني وبين مبرمج شغال معي عن بعد؟ أبي صيغة جاهزة ومنظمة.
"""

if __name__ == "__main__":
    print("⏳ جاري تحليل السوق واكتشاف أفضل 10 فرص بالذكاء الاصطناعي...")
    market_report = analyze_market_data(sample_scraped_data)
    print("\n================ 📈 تقرير رادار السوق الاحترافي (أفضل 10 فرص) ================\n")
    print(market_report)
    print("\n==============================================================================\n")
