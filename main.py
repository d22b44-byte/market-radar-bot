import os
from openai import OpenAI

# ضع مفتاح الـ API الخاص بك المبتدئ بـ sk- بين القوسين أدناه مكان الكلمة المكتوبة
API_KEY = os.environ.get("OPENAI_API_KEY")


client = OpenAI(api_key=API_KEY)

def analyze_market_data(raw_data):
    system_instruction = (
        "أنت خبير محترف في أبحاث السوق وتحليل البيانات الرقمية والمشاريع الناشئة (SaaS). "
        "مهمتك هي تحليل البيانات الخام القادمة من منصات التواصل ومواقع العمل الحر، "
        "واستخراج أكثر الخدمات الرقمية طلباً من قبل الأفراد والمؤسسات الصغيرة. "
        "يجب أن تركز على الخدمات التي يسهل أتمتتها بالكامل عبر بوت (AI Agent) دون تدخل بشري. "
        "قم بتنظيم التقرير النهائي في نقاط واضحة تشمل: اسم الخدمة، نسبة الطلب التقريبية بناءً على البيانات، "
        "وتقييم سهولة الأتمتة من 10 مع ذكر السبب والتوصية النهائية لأول 3 خدمات نبدأ بها."
    )
    try:
        response = client.chat.completions.create(
            model="gpt-4-turbo", # تم تحديث النموذج ليعمل بأعلى كفاءة مع المفاتيح الجديدة
            messages=[
                {"role": "system", "content": system_instruction},
                {"role": "user", "content": f"إليك البيانات الخام المجمعة من السوق للتحليل والفرز:\n\n{raw_data}"}
            ],
            temperature=0.3
        )
        return response.choices[0].message.content
    except Exception as e:
        return f"حدث خطأ أثناء الاتصال بالـ API: {str(e)}"

sample_scraped_data = """
- تغريدة 1: يا جماعة أبي أحد يترجم لي هذا الملف الإنجليزي لغة عربية احترافية بدون ترجمة جوجل ركيكة، ضروري اليوم.
- مستخدم في مستقل: مطلوب كاتب محتوى يجهز لي خطة تسويقية وتغريدات وسكريبتات تيك توك لمتجر عطور بشكل أسبوعي.
- تغريدة 2: كيف أقدر أعبي نموذج الجوازات الجديد حق التابعين؟ كل شوية يطلع لي خطأ وأنا أعبي البيانات يدوياً.
- تعليق تيك توك: أنا عندي اجتماع زوم ساعتين وأبي أحد يفرغه لي ويفرز لي النقاط المهمة لأن ما عندي وقت أسمعه كله.
- تغريدة 3: مطلوب مصمم لوقو (شعار) سريع وبسيط لمقهى جديد، الميزانية محدودة والتسليم فوري.
- مستخدم في خمسات: أبحث عن شخص يعدل لي السيرة الذاتية حقتي لتتوافق مع نظام الـ ATS للشركات الكبيرة.
- تغريدة 4: كيف أصيغ عقد اتفاقية عدم إفصاح (NDA) بيني وبين مبرمج شغال معي عن بعد؟ أبي صيغة جاهزة ومنظمة.
"""

if __name__ == "__main__":
    print("⏳ جاري تحليل السوق واكتشاف الفرص بالذكاء الاصطناعي...")
    market_report = analyze_market_data(sample_scraped_data)
    print("\n================ 📈 تقرير رادار السوق الاحترافي ================\n")
    print(market_report)
    print("\n=================================================================\n")
